#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

# ######## !!!! This script can not be automatically run at the moment.
#
# We use the evaluation script from https://github.com/s-malan/evaluation/blob/main/boundary_eval.py
# Please download the script and install dependencies
#
# Simon's evaluation script has been found to work with python=3.10 with additional following dependencies
#      pip install praat-textgrids numpy tqdm
# You could create a separate virtualenv, and setup `python_bin` as shown below.
#
# For evaluation, we use the another set of alignments, that were generated by Simon for reproducibily.
# The original alignment can be download from: https://github.com/s-malan/evaluation/releases/tag/v0.1.0
# However, the orignal alignment format is not compatible with the evaluation script.
# We realse a compatible alignment at:
## ####### !!!!

reference_base_dir=${REFERENCE_DIR:-${repo_root}/alignments/Librispeech-Simon-flatten}
evaluation_script="${EVALUATION_SCRIPT:-${repo_root}/Simon_scripts/evaluation/boundary_eval.py}"
python_bin="${PYTHON_BIN:-${repo_root}/Simon_scripts/evaluation/venv/bin/python}"
segmentation_dir="${SEGMENTATION_DIR:-${repo_root}/OUTPUT/peak_detection_tune}"

echo "exp 3c evaluate segmentation"
echo "segmentation dir: ${segmentation_dir}"

testsets=(dev test)
if [[ -n "${TESTSET:-}" ]]; then
    testsets=("$TESTSET")
fi

for testset in "${testsets[@]}"; do
    segmentation_inference_dirs=(
        "${segmentation_dir}/Z_CPCA/hubert-base-ls960/09/${testset}_word-space"
        "${segmentation_dir}/LEACE/hubert-base-ls960/09/${testset}_word-space"
        "${segmentation_dir}/Z_CPCA/hubert-base-random/09/${testset}_word-space"
        "${segmentation_dir}/LEACE/hubert-base-random/09/${testset}_word-space"
    )

    for segmentation_inference_dir in "${segmentation_inference_dirs[@]}"; do
        for alignment_type in word; do
            reference_dir="${reference_base_dir}/${testset}-clean-flatten/"
            out_dir="${segmentation_inference_dir}_eval/${alignment_type}-boundary"
            echo "${out_dir}"
            if [ ! -d "${out_dir}" ]; then
                mkdir -p "${out_dir}"
            fi

            job_pids=()
            for config_dir in "${segmentation_inference_dir}"/*/; do
                [[ -d "${config_dir}" ]] || continue
                config_id="$(basename "${config_dir}")"
                "${python_bin}" "${evaluation_script}" "${config_dir}" "${reference_dir}" \
                    --alignment_type="${alignment_type}" --tolerance 1 \
                    > "${out_dir}/${config_id}.res" &
                job_pids+=("$!")
            done
            for job_pid in "${job_pids[@]}"; do
                wait "${job_pid}" || exit 1
            done
        done
    done
done
